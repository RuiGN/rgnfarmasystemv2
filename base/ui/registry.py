def get_modules():
    return MODULES


def get_visible_modules(user):
    if not getattr(user, 'is_authenticated', False):
        return ()
    return tuple(
        replace(module, resources=visible_resources)
        for module in MODULES
        if module.show_in_navigation and (visible_resources := module.visible_resources(user))
    )


def get_module(module_slug):
    for module in MODULES:
        if module.slug == module_slug:
            return module
    return None


def get_resource(module_slug, resource_slug):
    module = get_module(module_slug)
    if module is None:
        return None

    for resource in module.resources:
        if resource.slug == resource_slug:
            return resource
    return None
