@dataclass(frozen=True)
class InlineResourceConfig:
    key: str
    title: str
    child_model: type[Model]
    parent_field: str
    fields: tuple[str, ...]
    description: str = ''
    add_label: str = 'Adicionar item'
    extra: int = 1
    actor_field: str | None = None
    inline_style: str = 'stacked'  # 'stacked' or 'tabular'
    # Índice da aba no formulário; None mantém o inline após as abas do próprio modelo.
    position: int | None = None
    read_only_fields: tuple[str, ...] = ()
    is_instance_mutable: Callable[[Model], bool] | None = None

    @property
    def app_label(self):
        return self.child_model._meta.app_label

    @property
    def model_name(self):
        return self.child_model._meta.model_name

    def can_add(self, user):
        return _user_has_model_permission(user, self.child_model, 'add')

    def can_view(self, user):
        return _user_has_model_permission(user, self.child_model, 'view')

    def can_change(self, user):
        return _user_has_model_permission(user, self.child_model, 'change')

    def can_delete(self, user):
        if requires_gxp_retention(self.child_model):
            return False
        return _user_has_model_permission(user, self.child_model, 'delete')


ResourceQuerysetScope = Callable[[Any, QuerySet], QuerySet]


def _unscoped_resource_queryset(request: Any, queryset: QuerySet) -> QuerySet:
    """Mantém o comportamento padrão para recursos sem escopo por usuário."""

    del request
    return queryset


def _workflow_notification_recipient_scope(
    request: Any,
    queryset: QuerySet,
) -> QuerySet:
    """Restringe notificações de workflow ao destinatário autenticado."""

    return queryset.filter(recipient=request.user)


def _protected_file_scope(request, queryset):
    from files.selectors import accessible_protected_files

    return queryset.filter(pk__in=accessible_protected_files(request.user).values('pk'))


def _file_related_scope(request, queryset):
    from files.selectors import accessible_protected_files

    permission = 'manage' if queryset.model is ProtectedFileAccessRule else 'view'
    return queryset.filter(
        protected_file_id__in=accessible_protected_files(request.user, permission).values('pk')
    )


def _chat_owner_scope(request, queryset):
    if not request.user.is_authenticated or not request.user.is_active:
        return queryset.none()
    owner_field = 'created_by' if queryset.model is RAGChatSession else 'session__created_by'
    return queryset.filter(**{owner_field: request.user})


@dataclass(frozen=True)
class ResourceConfig:
    slug: str
    label: str
    model: type[Model]
    list_display: tuple[str, ...]
    search_fields: tuple[str, ...] = ()
    form_fields: tuple[str, ...] | None = None
    inlines: tuple[InlineResourceConfig, ...] = field(default_factory=tuple)
    read_only: bool = False
    staff_only_mutations: bool = False
    is_executable: bool = False
    audit_trail: bool = False
    has_tree_view: bool = False
    has_kanban_view: bool = False
    has_document_viewer: bool = False
    has_gantt_view: bool = False
    has_chat_view: bool = False
    update_form_fields: tuple[str, ...] | None = None
    form_base: type[forms.ModelForm] | None = None
    actor_field: str = ''
    reuse_route_name: str = ''
    reuse_permissions: tuple[str, ...] = field(default_factory=tuple)
    view_permission_action: str = 'view'
    advanced_filter_fields: tuple[str, ...] = field(default_factory=tuple)
    queryset_scope: ResourceQuerysetScope = _unscoped_resource_queryset
    allow_delete: bool = True
    # Recursos cujo registro nasce de um pai (o pai define a FK obrigatória).
    allow_create: bool = True
    # Explica de onde vem o registro quando não há formulário em branco.
    create_hint: str = ''

    @property
    def app_label(self):
        return self.model._meta.app_label

    @property
    def model_name(self):
        return self.model._meta.model_name

    def permission_name(self, action):
        return f'{self.app_label}.{action}_{self.model_name}'

    def can_view(self, user):
        return _user_has_model_permission(user, self.model, self.view_permission_action)

    def can_add(self, user):
        return self.allow_create and self._can_write(user, 'add')

    def can_change(self, user):
        return self._can_write(user, 'change')

    def can_delete(self, user):
        if not self.allow_delete or requires_gxp_retention(self.model):
            return False
        return self._can_write(user, 'delete')

    def can_mutate(self, user):
        return self.can_add(user) or self.can_change(user) or self.can_delete(user)

    def can_reuse(self, user):
        return bool(
            self.reuse_route_name
            and self.can_view(user)
            # Reuso copia um registro existente, que já traz o pai preenchido:
            # depende da permissão de inclusão, não do formulário em branco.
            and self._can_write(user, 'add')
            and user.has_perms(self.reuse_permissions)
        )

    def _can_write(self, user, action):
        if self.read_only:
            return False
        if self.staff_only_mutations and not getattr(user, 'is_staff', False):
            return False
        return _user_has_model_permission(user, self.model, action)

    def get_queryset(self, request):
        queryset = self.model._default_manager.all()
        return self.queryset_scope(request, queryset)


@dataclass(frozen=True)
class ModuleConfig:
    slug: str
    label: str
    description: str
    icon: str = 'feather-grid'
    resources: tuple[ResourceConfig, ...] = field(default_factory=tuple)
    operational_permission: str = ''
    show_in_navigation: bool = True

    def visible_resources(self, user):
        return tuple(resource for resource in self.resources if resource.can_view(user))

    def can_view(self, user):
        return bool(self.visible_resources(user)) or bool(
            self.operational_permission and user.has_perm(self.operational_permission)
        )


def _user_has_model_permission(user, model, action):
    if not getattr(user, 'is_authenticated', False) or not getattr(user, 'is_active', False):
        return False
    return user.has_perm(f'{model._meta.app_label}.{action}_{model._meta.model_name}')


